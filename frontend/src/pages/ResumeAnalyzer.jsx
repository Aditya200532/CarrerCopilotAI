import { useRef, useState } from 'react';
import { UploadCloud, FileText, Trash2, Loader2, CheckCircle2, XCircle, Sparkles, Clock3 } from 'lucide-react';
import { endpoints } from '../api/client.js';
import { useFetch, useAnalysisPolling } from '../hooks/useApi.js';
import { PageLoader, ErrorBanner, SectionHeader, Badge, Progress } from '../components/ui.jsx';

export default function ResumeAnalyzer() {
  const { data: resumes, loading, error, refetch } = useFetch(() => endpoints.resumes.list({}), []);
  const [uploading, setUploading] = useState(false);
  const [uploadProgress, setUploadProgress] = useState(0);
  const [uploadError, setUploadError] = useState(null);
  const [pollId, setPollId] = useState(null);
  const fileRef = useRef(null);

  const primary = resumes?.find((r) => r.isPrimary) || resumes?.[0];
  const { analysis, done, failed } = useAnalysisPolling(pollId || primary?.analysis?.analysis);

  // Resume list already tells us status; polling refines it live.
  const liveStatus = pollId ? analysis?.status : primary?.analysis?.status;
  const result = analysis?.result || null;

  const onFile = async (e) => {
    const file = e.target.files?.[0];
    if (!file) return;
    setUploading(true); setUploadError(null); setUploadProgress(0);
    try {
      const res = await endpoints.resumes.upload(file, setUploadProgress);
      setPollId(res.data.analysisId);
      refetch();
    } catch (err) {
      setUploadError(err.message);
    } finally {
      setUploading(false);
      if (fileRef.current) fileRef.current.value = '';
    }
  };

  const remove = async (id) => {
    await endpoints.resumes.remove(id);
    refetch();
  };

  if (loading) return <PageLoader />;

  return (
    <div className="space-y-8">
      <div>
        <h1 className="page-title">Resume Analyzer</h1>
        <p className="page-subtitle">
          Uploads are processed by a background AI worker (queue + retry). You can leave the page — a notification arrives when it's done.
        </p>
      </div>

      <ErrorBanner message={error || uploadError} />

      {/* Upload card */}
      <div className="card p-6">
        <SectionHeader title="Upload resume" subtitle="PDF or TXT, max 5MB. Your newest upload becomes primary." />
        <label className={`flex cursor-pointer flex-col items-center justify-center rounded-2xl border-2 border-dashed p-10 text-center transition ${uploading ? 'border-brand-400 bg-brand-50/50' : 'border-slate-300 hover:border-brand-400 hover:bg-slate-50'}`}>
          <input ref={fileRef} type="file" accept=".pdf,.txt" className="hidden" onChange={onFile} disabled={uploading} />
          {uploading ? (
            <>
              <Loader2 className="mb-3 animate-spin text-brand-600" size={32} />
              <div className="text-sm font-medium text-slate-700">Uploading… {uploadProgress}%</div>
              <Progress value={uploadProgress} className="mt-3 !w-64" />
            </>
          ) : (
            <>
              <UploadCloud className="mb-3 text-slate-400" size={32} />
              <div className="text-sm font-medium text-slate-700">Click to upload your resume</div>
              <div className="mt-1 text-xs text-slate-400">PDF or TXT · analysis starts automatically via the worker queue</div>
            </>
          )}
        </label>
      </div>

      {/* Current resume + status */}
      {primary && (
        <div className="card p-6">
          <SectionHeader title="Primary resume" />
          <div className="flex flex-wrap items-center justify-between gap-4 rounded-xl border border-slate-200 p-4">
            <div className="flex items-center gap-3">
              <div className="flex h-10 w-10 items-center justify-center rounded-xl bg-slate-100 text-slate-500"><FileText size={20} /></div>
              <div>
                <div className="text-sm font-semibold text-slate-800">{primary.filename}</div>
                <div className="text-xs text-slate-400">
                  {primary.sizeBytes ? `${(primary.sizeBytes / 1024).toFixed(0)} KB · ` : ''}
                  uploaded {new Date(primary.createdAt).toLocaleDateString()}
                </div>
              </div>
            </div>
            <div className="flex items-center gap-3">
              <StatusChip status={liveStatus} />
              <button className="btn-ghost text-rose-500" onClick={() => remove(primary._id)}><Trash2 size={16} /> Remove</button>
            </div>
          </div>
        </div>
      )}

      {/* Analysis result */}
      {result && (
        <div className="space-y-6">
          <div className="card p-6">
            <SectionHeader title="AI analysis" subtitle={result.source === 'local' ? 'Generated by local fallback analyzer (no LLM key configured)' : 'Generated by the LLM pipeline'} />
            <div className="mb-6 flex items-center gap-6">
              <ScoreRing score={result.readinessScore} />
              <div>
                <div className="text-sm font-semibold text-slate-800">Placement readiness</div>
                <p className="mt-1 max-w-md text-sm text-slate-500">
                  A composite of skills coverage, project depth and resume quality. Use the tips below to improve it.
                </p>
              </div>
            </div>

            <div className="grid gap-6 md:grid-cols-2">
              <ListBlock tone="green" icon={CheckCircle2} title="Strengths" items={result.strengths} />
              <ListBlock tone="red" icon={XCircle} title="Weaknesses" items={result.weaknesses} />
              <ListBlock tone="amber" icon={Sparkles} title="Missing essentials" items={result.missingEssentials} />
              <ListBlock tone="blue" icon={Sparkles} title="Resume tips" items={result.resumeTips} />
            </div>

            {result.projectFeedback && (
              <div className="mt-6 rounded-xl bg-slate-50 p-4 text-sm text-slate-600">
                <span className="font-semibold text-slate-800">Project feedback: </span>{result.projectFeedback}
              </div>
            )}

            {result.skills?.length > 0 && (
              <div className="mt-6">
                <div className="mb-2 text-sm font-semibold text-slate-700">Skills detected</div>
                <div className="flex flex-wrap gap-1.5">
                  {result.skills.map((s) => <Badge key={s} tone="brand">{s}</Badge>)}
                </div>
              </div>
            )}
            {result.suitableRoles?.length > 0 && (
              <div className="mt-4 text-sm text-slate-500">
                <span className="font-semibold text-slate-700">Suitable roles: </span>{result.suitableRoles.join(', ')}
              </div>
            )}
          </div>
        </div>
      )}

      {/* History */}
      {resumes?.length > 1 && (
        <div className="card p-6">
          <SectionHeader title="Upload history" />
          <ul className="divide-y divide-slate-100">
            {resumes.map((r) => (
              <li key={r._id} className="flex items-center justify-between py-3">
                <div className="flex items-center gap-3">
                  <FileText size={16} className="text-slate-400" />
                  <span className="text-sm text-slate-700">{r.filename}</span>
                  {r.isPrimary && <Badge tone="brand">primary</Badge>}
                </div>
                <StatusChip status={r.analysis?.status} />
              </li>
            ))}
          </ul>
        </div>
      )}
    </div>
  );
}

function StatusChip({ status }) {
  const map = {
    queued: { tone: 'amber', icon: Clock3, label: 'Queued' },
    processing: { tone: 'blue', icon: Loader2, label: 'Analyzing…' },
    completed: { tone: 'green', icon: CheckCircle2, label: 'Completed' },
    failed: { tone: 'red', icon: XCircle, label: 'Failed' },
    pending: { tone: 'slate', icon: Clock3, label: 'Pending' },
  };
  const s = map[status] || map.pending;
  return (
    <Badge tone={s.tone}>
      <s.icon size={12} className={status === 'processing' ? 'animate-spin' : ''} /> {s.label}
    </Badge>
  );
}

function ScoreRing({ score }) {
  const pct = ((score ?? 0) / 10) * 100;
  return (
    <div className="relative h-24 w-24 shrink-0">
      <svg viewBox="0 0 36 36" className="h-24 w-24 -rotate-90">
        <circle cx="18" cy="18" r="15.9" fill="none" stroke="#e2e8f0" strokeWidth="3.5" />
        <circle cx="18" cy="18" r="15.9" fill="none" stroke="#6366f1" strokeWidth="3.5"
          strokeDasharray={`${pct} 100`} strokeLinecap="round" />
      </svg>
      <div className="absolute inset-0 flex items-center justify-center text-lg font-bold text-slate-800">
        {score ?? '–'}<span className="text-xs font-medium text-slate-400">/10</span>
      </div>
    </div>
  );
}

function ListBlock({ tone, icon: Icon, title, items = [] }) {
  if (!items.length) return null;
  const color = { green: 'text-emerald-600', red: 'text-rose-600', amber: 'text-amber-600', blue: 'text-sky-600' }[tone];
  return (
    <div>
      <div className={`mb-2 flex items-center gap-2 text-sm font-semibold ${color}`}><Icon size={16} /> {title}</div>
      <ul className="space-y-1.5">
        {items.map((it, i) => <li key={i} className="text-sm leading-relaxed text-slate-600">• {it}</li>)}
      </ul>
    </div>
  );
}
